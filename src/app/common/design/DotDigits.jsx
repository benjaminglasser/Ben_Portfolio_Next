/**
 * Renders a short string as dot-matrix letters and digits.
 * `pitch` is the distance between dot centers in px.
 * Unlit dots are drawn faintly (ghost) so it reads like a real display.
 * `blinkColon` lets CSS pulse any ":" for a live clock tick.
 */
const DotDigits = ({
  value,
  pitch = 3,
  ghost = true,
  blinkColon = false,
  label,
  className = "",
}) => {
  const chars = String(value).toUpperCase().split("");
  const radius = pitch * 0.36;
  let x = 0;
  const dots = [];

  chars.forEach((ch, ci) => {
    const glyph = GLYPHS[ch] || GLYPHS[" "];
    const width = glyph[0].length;
    glyph.forEach((row, ry) => {
      row.split("").forEach((bit, rx) => {
        const lit = bit === "1";
        if (!lit && !ghost) return;
        let cls = "dot-off";
        if (lit) cls = ch === ":" && blinkColon ? "dot-on dot-colon" : "dot-on";
        dots.push(
          <circle
            key={`${ci}-${rx}-${ry}`}
            cx={(x + rx) * pitch + pitch / 2}
            cy={ry * pitch + pitch / 2}
            r={radius}
            className={cls}
            style={{ "--c": x + rx, "--ch": ci }}
          />
        );
      });
    });
    x += width + 1;
  });

  const totalWidth = Math.max(0, (x - 1) * pitch);
  const totalHeight = 7 * pitch;

  return (
    <span className={`dot-digits ${className}`}>
      <svg
        width={totalWidth}
        height={totalHeight}
        viewBox={`0 0 ${totalWidth} ${totalHeight}`}
        aria-hidden="true"
        focusable="false"
      >
        {dots}
      </svg>
      <span className="sr-only">{label ?? value}</span>
    </span>
  );
};

export default DotDigits;
